#!/usr/bin/env bash
# Benchmark report generator
# Aggregates benchmark results and produces a readable comparison report
#
# Usage: report.sh [--results-dir <dir>]
#
# Bash 3.2 compatible. Requires: jq

set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_UNDERSTAND_DIR="$(dirname "$SCRIPT_DIR")"

. "$REPO_UNDERSTAND_DIR/lib/util.sh"

RESULTS_DIR="$SCRIPT_DIR/results"

while [ $# -gt 0 ]; do
    case "$1" in
        --results-dir)
            shift
            RESULTS_DIR="$1"
            ;;
        --help|-h)
            echo "Usage: $(basename "$0") [--results-dir <dir>]"
            echo "Generates a comparison report from benchmark results."
            exit 0
            ;;
        *)
            log_error "Unknown argument: $1"
            exit 1
            ;;
    esac
    shift
done

require_command "jq" "brew install jq"

[ -d "$RESULTS_DIR" ] || { log_error "Results directory not found: $RESULTS_DIR"; exit 1; }

VALID_RESULTS_FILE_LIST=$(mktemp "${TMPDIR:-/tmp}/benchmark-results-XXXXXX")
find "$RESULTS_DIR" -name '*.json' -type f ! -name '*_raw.json' ! -name '*_prompt.txt' 2>/dev/null | while IFS= read -r f; do
    [ -z "$f" ] && continue
    if jq -e '
        (.task // "") != "" and
        (.model // "") != "" and
        (.condition == "without" or .condition == "with")
    ' "$f" >/dev/null 2>&1; then
        echo "$f"
    fi
done > "$VALID_RESULTS_FILE_LIST"

RESULT_COUNT=$(wc -l < "$VALID_RESULTS_FILE_LIST" | tr -d ' ')
[ "$RESULT_COUNT" -eq 0 ] && {
    rm -f "$VALID_RESULTS_FILE_LIST"
    log_error "No valid benchmark result files found in $RESULTS_DIR"
    exit 1
}

REPORT_FILE="$RESULTS_DIR/benchmark-report.md"

log_info "Generating benchmark report from $RESULT_COUNT result files..."

TASKS_FILE=$(mktemp "${TMPDIR:-/tmp}/benchmark-tasks-XXXXXX")
while IFS= read -r f; do
    jq -r '"\(.task)\t\(.model // "unknown")"' "$f" 2>/dev/null
done < "$VALID_RESULTS_FILE_LIST" | sort -u > "$TASKS_FILE"

# Helper: format numbers with thousands separator (pure bash, works on macOS)
fmt_num() {
    local n="$1"
    case "$n" in
        *.*) printf "%s" "$n"; return ;;
    esac
    if [ "$n" -eq 0 ] 2>/dev/null; then
        printf "0"
        return
    fi
    printf "%'d" "$n" 2>/dev/null || printf "%s" "$n"
}

# Helper: compute average (integer division)
avg() {
    local sum="$1"
    local count="$2"
    if [ "$count" -gt 0 ]; then
        echo $(( sum / count ))
    else
        echo 0
    fi
}

# Helper: compute delta string (lower-is-better by default)
delta_str() {
    local baseline="$1"
    local value="$2"
    local higher_is_better="${3:-false}"

    if [ "$baseline" -eq 0 ] || [ "$value" -eq 0 ]; then
        echo "n/a"
        return
    fi
    if [ "$baseline" -eq "$value" ]; then
        echo "0%"
        return
    fi

    if [ "$baseline" -gt "$value" ]; then
        local pct=$(( (baseline - value) * 100 / baseline ))
        if [ "$higher_is_better" = "true" ]; then
            echo "-${pct}%"
        else
            echo "-${pct}% *"
        fi
    else
        local pct=$(( (value - baseline) * 100 / baseline ))
        if [ "$higher_is_better" = "true" ]; then
            echo "+${pct}% *"
        else
            echo "+${pct}%"
        fi
    fi
}

cat > "$REPORT_FILE" <<'HEADER'
<!-- GENERATED by benchmark report.sh -->
# Benchmark Comparison Report

Compares agent performance: baseline (no scaffolding) vs with scaffolding.
`*` = better than baseline.

HEADER

while IFS=$'\t' read -r task model; do
    [ -z "$task" ] && continue
    [ -z "$model" ] && model="unknown"

    for cond in without with; do
        for metric in duration_seconds input_tokens output_tokens total_tokens num_turns cost_usd accuracy completeness hallucination_count; do
            eval "${cond}_${metric}_sum=0"
            eval "${cond}_${metric}_count=0"
        done
    done

    while IFS= read -r f; do
        [ -z "$f" ] && continue
        file_task=$(jq -r '.task' "$f" 2>/dev/null)
        file_cond=$(jq -r '.condition' "$f" 2>/dev/null)
        file_model=$(jq -r '.model // "unknown"' "$f" 2>/dev/null)
        [ "$file_task" != "$task" ] && continue
        [ "$file_model" != "$model" ] && continue

        for metric in duration_seconds input_tokens output_tokens total_tokens num_turns; do
            val=$(jq -r ".$metric // 0" "$f" 2>/dev/null)
            eval "${file_cond}_${metric}_sum=\$(( ${file_cond}_${metric}_sum + val ))"
            eval "${file_cond}_${metric}_count=\$(( ${file_cond}_${metric}_count + 1 ))"
        done

        cost_raw=$(jq -r '.cost_usd // 0' "$f" 2>/dev/null)
        cost_cents=$(echo "$cost_raw" | awk '{printf "%d", $1 * 100}')
        eval "${file_cond}_cost_usd_sum=\$(( ${file_cond}_cost_usd_sum + cost_cents ))"
        eval "${file_cond}_cost_usd_count=\$(( ${file_cond}_cost_usd_count + 1 ))"

        for metric in accuracy completeness hallucination_count; do
            val=$(jq -r ".$metric // empty" "$f" 2>/dev/null)
            [ -z "$val" ] && continue
            eval "${file_cond}_${metric}_sum=\$(( ${file_cond}_${metric}_sum + val ))"
            eval "${file_cond}_${metric}_count=\$(( ${file_cond}_${metric}_count + 1 ))"
        done
    done < "$VALID_RESULTS_FILE_LIST"

    for cond in without with; do
        for metric in duration_seconds input_tokens output_tokens total_tokens num_turns cost_usd accuracy completeness hallucination_count; do
            eval "${cond}_${metric}=\$(avg \$${cond}_${metric}_sum \$${cond}_${metric}_count)"
        done
    done

    cat >> "$REPORT_FILE" <<EOF
## $task (model: $model)

### Performance

| Metric   | Without Scaffolding | With Scaffolding              |
|----------|--------------------:|------------------------------:|
| Duration | ${without_duration_seconds}s | ${with_duration_seconds}s ($(delta_str "$without_duration_seconds" "$with_duration_seconds")) |
| Tokens   | $(fmt_num "$without_total_tokens") | $(fmt_num "$with_total_tokens") ($(delta_str "$without_total_tokens" "$with_total_tokens")) |
| Turns    | $without_num_turns | $with_num_turns ($(delta_str "$without_num_turns" "$with_num_turns")) |
| Cost     | \$$(echo "$without_cost_usd" | awk '{printf "%.2f", $1/100}') | \$$(echo "$with_cost_usd" | awk '{printf "%.2f", $1/100}') ($(delta_str "$without_cost_usd" "$with_cost_usd")) |

EOF

    if [ "$without_accuracy_count" -gt 0 ] || [ "$with_accuracy_count" -gt 0 ]; then
        cat >> "$REPORT_FILE" <<EOF
### Quality (judge-scored)

| Metric         | Without Scaffolding | With Scaffolding              |
|----------------|--------------------:|------------------------------:|
| Accuracy       | $without_accuracy/5 | $with_accuracy/5 ($(delta_str "$without_accuracy" "$with_accuracy" true)) |
| Completeness   | $without_completeness/5 | $with_completeness/5 ($(delta_str "$without_completeness" "$with_completeness" true)) |
| Hallucinations | $without_hallucination_count | $with_hallucination_count ($(delta_str "$without_hallucination_count" "$with_hallucination_count")) |

EOF
    fi

    echo "Runs: without=${without_duration_seconds_count}, with=${with_duration_seconds_count}" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"

done < "$TASKS_FILE"

rm -f "$TASKS_FILE" "$VALID_RESULTS_FILE_LIST"

cat >> "$REPORT_FILE" <<'GUIDE'
---

**Reading this report:** Lower duration/tokens/cost is better. Higher accuracy/completeness
is better. `*` marks values that improved vs baseline. Hallucinations: lower is better.
For reliable results, run each condition 3+ times.
GUIDE

log_success "Report written to: $REPORT_FILE"
