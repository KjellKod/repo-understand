#!/usr/bin/env bash
# Benchmark report generator
# Aggregates benchmark results and produces a markdown comparison table
#
# Usage: report.sh [--results-dir <dir>]
#
# Bash 3.2 compatible. Requires: jq

set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_UNDERSTAND_DIR="$(dirname "$SCRIPT_DIR")"

. "$REPO_UNDERSTAND_DIR/lib/util.sh"

RESULTS_DIR="$SCRIPT_DIR/results"

while [ $# -gt 0 ]; do
    case "$1" in
        --results-dir)
            shift
            RESULTS_DIR="$1"
            ;;
        --help|-h)
            echo "Usage: $(basename "$0") [--results-dir <dir>]"
            echo "Generates a comparison report from benchmark results."
            exit 0
            ;;
        *)
            log_error "Unknown argument: $1"
            exit 1
            ;;
    esac
    shift
done

require_command "jq" "brew install jq"

[ -d "$RESULTS_DIR" ] || { log_error "Results directory not found: $RESULTS_DIR"; exit 1; }

RESULT_COUNT=$(find "$RESULTS_DIR" -name '*.json' -type f 2>/dev/null | wc -l | tr -d ' ')
[ "$RESULT_COUNT" -eq 0 ] && { log_error "No results found in $RESULTS_DIR"; exit 1; }

REPORT_FILE="$RESULTS_DIR/benchmark-report.md"

log_info "Generating benchmark report from $RESULT_COUNT result files..."

# Collect unique task+model combos
TASKS_FILE=$(mktemp "${TMPDIR:-/tmp}/benchmark-tasks-XXXXXX")
find "$RESULTS_DIR" -name '*.json' -type f 2>/dev/null | while IFS= read -r f; do
    jq -r '"\(.task)\t\(.model // "unknown")"' "$f" 2>/dev/null
done | sort -u > "$TASKS_FILE"

cat > "$REPORT_FILE" <<'HEADER'
<!-- GENERATED by benchmark report.sh -->
# Benchmark Comparison Report

## Overview

This report compares AI agent performance on identical tasks with and without
repository understanding scaffolding generated by `repo-understand.sh`.

Agents run in full agent mode with file access (Read, Glob, Grep). The key
insight is whether pre-generated docs reduce the time and tokens an agent
needs to explore the codebase.

## Results

HEADER

# For each task+model combo, show with vs without comparison
while IFS=$'\t' read -r task model; do
    [ -z "$task" ] && continue
    [ -z "$model" ] && model="unknown"

    echo "### Task: $task (model: $model)" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"

    # Performance metrics table
    echo "**Performance**" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
    echo "| Metric | Without Scaffolding | With Scaffolding | Delta |" >> "$REPORT_FILE"
    echo "|--------|--------------------:|------------------:|------:|" >> "$REPORT_FILE"

    for metric in duration_seconds input_tokens output_tokens total_tokens num_turns; do
        without_sum=0
        without_count=0
        with_sum=0
        with_count=0

        while IFS= read -r f; do
            [ -z "$f" ] && continue
            file_task=$(jq -r '.task' "$f" 2>/dev/null)
            file_cond=$(jq -r '.condition' "$f" 2>/dev/null)
            file_model=$(jq -r '.model // "unknown"' "$f" 2>/dev/null)
            [ "$file_task" != "$task" ] && continue
            [ "$file_model" != "$model" ] && continue

            val=$(jq -r ".$metric // 0" "$f" 2>/dev/null)
            if [ "$file_cond" = "without" ]; then
                without_sum=$((without_sum + val))
                without_count=$((without_count + 1))
            elif [ "$file_cond" = "with" ]; then
                with_sum=$((with_sum + val))
                with_count=$((with_count + 1))
            fi
        done < <(find "$RESULTS_DIR" -name '*.json' -type f 2>/dev/null)

        # Compute averages
        without_avg=0
        with_avg=0
        if [ "$without_count" -gt 0 ]; then
            without_avg=$((without_sum / without_count))
        fi
        if [ "$with_count" -gt 0 ]; then
            with_avg=$((with_sum / with_count))
        fi

        # Compute delta
        delta="n/a"
        if [ "$without_avg" -gt 0 ] && [ "$with_avg" -gt 0 ]; then
            if [ "$without_avg" -gt "$with_avg" ]; then
                pct=$(( (without_avg - with_avg) * 100 / without_avg ))
                delta="-${pct}%"
            elif [ "$with_avg" -gt "$without_avg" ]; then
                pct=$(( (with_avg - without_avg) * 100 / without_avg ))
                delta="+${pct}%"
            else
                delta="0%"
            fi
        fi

        # Format metric name
        display_metric=""
        case "$metric" in
            duration_seconds) display_metric="Duration (s)" ;;
            input_tokens) display_metric="Input Tokens" ;;
            output_tokens) display_metric="Output Tokens" ;;
            total_tokens) display_metric="Total Tokens" ;;
            num_turns) display_metric="Agent Turns" ;;
        esac

        echo "| $display_metric | $without_avg | $with_avg | $delta |" >> "$REPORT_FILE"
    done

    echo "" >> "$REPORT_FILE"
    echo "Runs: without=$without_count, with=$with_count" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"

    # Accuracy table (if judge scores exist)
    has_accuracy="false"
    while IFS= read -r f; do
        [ -z "$f" ] && continue
        file_task=$(jq -r '.task' "$f" 2>/dev/null)
        file_model=$(jq -r '.model // "unknown"' "$f" 2>/dev/null)
        [ "$file_task" != "$task" ] && continue
        [ "$file_model" != "$model" ] && continue
        acc=$(jq -r '.accuracy // empty' "$f" 2>/dev/null)
        if [ -n "$acc" ]; then
            has_accuracy="true"
            break
        fi
    done < <(find "$RESULTS_DIR" -name '*.json' -type f 2>/dev/null)

    if [ "$has_accuracy" = "true" ]; then
        echo "**Accuracy (judge-scored)**" >> "$REPORT_FILE"
        echo "" >> "$REPORT_FILE"
        echo "| Metric | Without Scaffolding | With Scaffolding | Delta |" >> "$REPORT_FILE"
        echo "|--------|--------------------:|------------------:|------:|" >> "$REPORT_FILE"

        for metric in accuracy completeness hallucination_count; do
            without_sum=0
            without_count=0
            with_sum=0
            with_count=0

            while IFS= read -r f; do
                [ -z "$f" ] && continue
                file_task=$(jq -r '.task' "$f" 2>/dev/null)
                file_cond=$(jq -r '.condition' "$f" 2>/dev/null)
                file_model=$(jq -r '.model // "unknown"' "$f" 2>/dev/null)
                [ "$file_task" != "$task" ] && continue
                [ "$file_model" != "$model" ] && continue

                val=$(jq -r ".$metric // empty" "$f" 2>/dev/null)
                [ -z "$val" ] && continue

                if [ "$file_cond" = "without" ]; then
                    without_sum=$((without_sum + val))
                    without_count=$((without_count + 1))
                elif [ "$file_cond" = "with" ]; then
                    with_sum=$((with_sum + val))
                    with_count=$((with_count + 1))
                fi
            done < <(find "$RESULTS_DIR" -name '*.json' -type f 2>/dev/null)

            without_avg=0
            with_avg=0
            if [ "$without_count" -gt 0 ]; then
                without_avg=$((without_sum / without_count))
            fi
            if [ "$with_count" -gt 0 ]; then
                with_avg=$((with_sum / with_count))
            fi

            delta="n/a"
            if [ "$without_avg" -gt 0 ] && [ "$with_avg" -gt 0 ]; then
                if [ "$metric" = "hallucination_count" ]; then
                    # For hallucinations, lower is better
                    if [ "$without_avg" -gt "$with_avg" ]; then
                        pct=$(( (without_avg - with_avg) * 100 / without_avg ))
                        delta="-${pct}%"
                    elif [ "$with_avg" -gt "$without_avg" ]; then
                        pct=$(( (with_avg - without_avg) * 100 / without_avg ))
                        delta="+${pct}%"
                    else
                        delta="0%"
                    fi
                else
                    # For accuracy/completeness, higher is better
                    if [ "$with_avg" -gt "$without_avg" ]; then
                        pct=$(( (with_avg - without_avg) * 100 / without_avg ))
                        delta="+${pct}%"
                    elif [ "$without_avg" -gt "$with_avg" ]; then
                        pct=$(( (without_avg - with_avg) * 100 / without_avg ))
                        delta="-${pct}%"
                    else
                        delta="0%"
                    fi
                fi
            fi

            display_metric=""
            case "$metric" in
                accuracy) display_metric="Accuracy (1-5)" ;;
                completeness) display_metric="Completeness (1-5)" ;;
                hallucination_count) display_metric="Hallucinations" ;;
            esac

            echo "| $display_metric | $without_avg | $with_avg | $delta |" >> "$REPORT_FILE"
        done

        echo "" >> "$REPORT_FILE"
    fi

done < "$TASKS_FILE"

rm -f "$TASKS_FILE"

# Add interpretation guide
cat >> "$REPORT_FILE" <<'GUIDE'

## How to read this report

**Duration** is the primary metric. Lower duration with scaffolding means
the agent reached its answer faster because it didn't need to explore as
many files.

**Agent Turns** shows how many tool-use round trips the agent needed.
Fewer turns with scaffolding means the generated docs provided enough
context to reduce exploration.

**Total Tokens** reflects the full session cost. With scaffolding, the
initial input is larger (the docs are in the repo), but total session
tokens should be lower if the agent explores less.

**Accuracy and Completeness** (if judged) show whether the agent's answer
was correct and thorough. Scaffolding should improve both by giving the
agent accurate structural information upfront.

**Hallucinations** (if judged) count fabricated claims. Agents without
scaffolding are more likely to guess at repo structure and get it wrong.

## Notes

- All runs use claude in agent mode with Read, Glob, Grep tools
- Token counts reflect the full agent session (all turns combined)
- For reliable comparison, run each condition 3+ times
- Judge scores require running `benchmark.sh --judge` on each result
GUIDE

log_success "Report written to: $REPORT_FILE"
